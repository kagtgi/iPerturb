from ipt.models.basis_hill import coef_from_k, cheb_clenshaw, fit_table
from ipt.models.hill import hill4

xs = torch.linspace(0, 1, 2001)
for r in (4, 8, 16, 32):
    tab = torch.as_tensor(fit_table(r), dtype=torch.float32)
