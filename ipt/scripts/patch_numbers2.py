"""Patch build_numbers.py: unique-target G2 statistics, approximation error, binomial/Wilcoxon, fallback and memory-ratio macros."""
from pathlib import Path

p = Path(__file__).parents[1] / "scripts" / "build_numbers.py"
s = p.read_text(encoding="utf8")

# 1) G2 at the level of unique targets (average the folds in which a target is tested)
s = s.replace(
    'return R[(R.model == model) & (R.graph == graph)].groupby(["fold", "target"]).pcc_c.mean()',
    'return R[(R.model == model) & (R.graph == graph)].groupby("target").pcc_c.mean()',
)

