"""Derived macros (sums, percentages) computed from numbers.tex / numbers2.tex; writes paper/numbers3.tex."""
import re
from pathlib import Path

P = Path(__file__).parents[1] / "paper"
BS = chr(92)
t = (P / "numbers.tex").read_text(encoding="utf8") + (P / "numbers2.tex").read_text(encoding="utf8")
d = dict(re.findall(r"data@(.+?)" + re.escape(BS) + r"endcsname\{(.*)\}", t))


def num(k):
    return float(d[k].replace(",", ""))


out = {
    "n_uniq_total": f"{int(num('k562_nuniq') + num('rpe1_nuniq')):,}",
    "mech_k562_real_h1_pct": f"{100 * num('mech_k562_real_h1'):.0f}",
    "mech_rpe1_real_h1_pct": f"{100 * num('mech_rpe1_real_h1'):.0f}",
    "mech_k562_signperm_h1_pct": f"{100 * num('mech_k562_signperm_h1'):.0f}",
    "mech_rpe1_signperm_h1_pct": f"{100 * num('mech_rpe1_signperm_h1'):.0f}",
}
lines = ["% generated by scripts/derived_numbers.py -- do not edit"]
lines += [f"{BS}expandafter{BS}def{BS}csname data@{k}{BS}endcsname{{{v}}}" for k, v in out.items()]
(P / "numbers3.tex").write_text("\n".join(lines) + "\n", encoding="utf8")
print(out)
